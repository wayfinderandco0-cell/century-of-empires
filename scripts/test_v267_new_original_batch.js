"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const crypto=require("node:crypto");
const gate=require("../terrain-grid/v267-art-factory-contract.js");
const base=JSON.parse(fs.readFileSync("terrain-grid/atlas-cells.json","utf8"));
const batch=JSON.parse(fs.readFileSync("terrain-grid/v267-original-art-batch-01/batch.json","utf8"));
const counts=gate.validateBatch(batch,base);
assert.equal(counts.candidateMetadata,8);
assert.equal(counts.originalArtComposed,1);
assert.equal(counts.visuallyReviewed,1);
assert.equal(counts.roadConnected,0);
assert.ok(counts.mobileWebkitRendered===0||counts.mobileWebkitRendered===1);
assert.equal(counts.historicallyVerified,0);
assert.equal(counts.nativePlayable,0);
assert.equal(counts.userApproved,0);
assert.equal(counts.netFinishedToday,0);
const cell=batch.cells.find(c=>c.id==="matrei-east-ridge");
assert.deepEqual(cell.origin,[3072,0]);
assert.equal(cell.visualQualityApproved,false);
assert.equal(cell.sourceProvenance.kind,"new-original-generated-art");
assert.equal(cell.sourceProvenance.nonUniformTreeWarp,false);
assert.equal(cell.sourceProvenance.historicalTopographyClaim,false);
assert.equal(cell.roadPorts.length,0);
assert.equal(batch.decorativeInlays.length,1);
const infill=batch.decorativeInlays[0];
assert.equal(infill.playable,false);
assert.equal(infill.sourceCell,"matrei-east-ridge");
assert.deepEqual(infill.roads,[]);
assert.deepEqual(infill.roadPorts,[]);
const bytes=fs.readFileSync(cell.art);
assert.equal(bytes.toString("ascii",0,4),"RIFF");
assert.equal(bytes.toString("ascii",8,12),"WEBP");
assert.ok(bytes.length>100000,"new original scene must be an actual detailed WebP");
assert.equal(crypto.createHash("sha256").update(bytes).digest("hex"),cell.assetSha256);
for(const c of batch.cells.filter(c=>c.id!==cell.id)){
 assert.equal(c.originalArtComposed,false);
 assert.ok(!c.art);
 assert.equal(c.roadPorts.length,0);
}
const engine=fs.readFileSync("terrain-grid/atlas-integrated.js","utf8");
assert.ok(engine.includes('focusedV267NewPilot=studyParams.get("originalArtPilot")==="v267-new"'));
assert.ok(engine.includes("terrain-grid/v267-original-art-batch-01/batch.json"));
assert.ok(engine.includes("if(photoMode||neighborPilotShown)"));
console.log("PASS: one NEW original V267-like scene, 7 metadata-only neighbors, zero invented routes/history/finished");
