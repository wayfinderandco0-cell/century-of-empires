"use strict";
const assert=require("node:assert/strict");
const data=require("./corridor-data.js");
const engine=require("./road-graph.js");
const graph=engine.build(data.corridors);
assert.equal(graph.verify.connected,true);
assert.equal(graph.verify.roadCount,1);
assert.ok(graph.verify.nodeCount>=20);
const find=id=>data.settlements.find(p=>p.id===id).point;
const a=find("matrei"),b=find("gries");
const route=graph.route(a,b);
assert.ok(route,"Matrei-to-Gries route exists");
assert.ok(route.meters>5000&&route.meters<18000,"Route length plausible for pilot");
assert.ok(engine.distance(route.coordinates[0],a)<.1);
assert.ok(engine.distance(route.coordinates.at(-1),b)<.1);
assert.ok(graph.route(b,a),"Bidirectional movement");
const first=graph.segments[12],t=.37;
const middle=[first.a[0]+(first.b[0]-first.a[0])*t,first.a[1]+(first.b[1]-first.a[1])*t];
const midRoute=graph.route(a,middle);
assert.ok(midRoute,"Mid-segment destination");
assert.ok(engine.distance(midRoute.coordinates.at(-1),middle)<.1,"Snap exactly to requested mid-road point");
const direct=graph.route(first.a,middle);
assert.ok(Math.abs(direct.meters-first.length*t)<2,"Same-segment routing distance");
assert.equal(graph.route([12,48],b),null,"Off-corridor destination rejected");
assert.equal(graph.route(a,[14,49]),null,"Off-corridor destination rejected");
assert.deepEqual(graph.geometry.features[0].geometry.coordinates,data.corridors[0].coordinates,
 "Rendered road uses exact coordinates as navigation segments");
const position=graph.interpolate(route.coordinates,route.meters*.52);
assert.ok(graph.nearest(position).meters<1,"Marching position stays exactly on visible road");
assert.ok(engine.distance(graph.interpolate(route.coordinates,route.meters*2),b)<.1,"Arrival clamps to destination");
assert.throws(()=>engine.build([{id:"bad",coordinates:[[11,47],[12,47]]},{id:"disconnected",coordinates:[[14,47],[15,47]]}]),/Disconnected/);
assert.throws(()=>engine.build([{id:"bad",coordinates:[[11,47],[11,47]]}]),/Zero length/);
console.log("PASS: geographic road graph, visible geometry identity, mid-road routing, interpolation, disconnected rejection");
console.log(JSON.stringify({nodes:graph.verify.nodeCount,segments:graph.verify.segments,matreiGriesKm:+(route.meters/1000).toFixed(2)}));